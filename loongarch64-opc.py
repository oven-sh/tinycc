#!/usr/bin/env python3
"""Generate loongarch64-opc.h, the LoongArch64 instruction table of tcc's
assembler, from the loongson-community/loongarch-opcodes database.

The database (https://github.com/loongson-community/loongarch-opcodes) is
licensed CC-BY-4.0 (tables) / MIT (code), which tcc's LGPL can carry; GNU
binutils' opcodes/loongarch-opc.c (GPLv3) is deliberately not the source.
The database renames a few instructions (sext.h for ext.w.h, ldox4 for ldptr,
...) and canonicalises operand order; this script uses the original manual
names (@orig_name) and assembly operand order (@orig_fmt), which is what
GNU as accepts.

Format notation (database README): D J K A are integer registers at bits 0, 5,
10, 15; F<i> C<i> are FP / condition-flag registers at index <i>; S/U start a
signed/unsigned immediate made of <i><len> fields concatenated MSB first;
index letters d j k a m n are bits 0 5 10 15 16 18; a trailing p<op><n> on an
immediate means the assembly value is imm+n (p) or imm<<n (s).

Usage: loongarch64-opc.py DBDIR > loongarch64-opc.h
"""
import glob
import os
import subprocess
import sys

# The user-mode subset: base integer, bit ops, multiply/divide, atomics,
# floating point and bound-check loads. SIMD (lsx/lasx), binary translation
# (lbt), virtualisation (lvz) and privileged instructions are left out.
FILES = ['la-base-32.txt', 'la-base-64.txt', 'la-bitops-32.txt', 'la-bitops-64.txt',
         'la-mul-32.txt', 'la-mul-64.txt', 'la-atomics-32.txt', 'la-atomics-64.txt',
         'la-fp.txt', 'la-fp-s.txt', 'la-fp-d.txt',
         'la-bound.txt', 'la-bound-64.txt', 'la-bound-fp-s.txt', 'la-bound-fp-d.txt']

FCSR_FMT = {'movgr2fcsr': 'QdJ', 'movfcsr2gr': 'DQj'}


def main():
    db = sys.argv[1]
    rev = subprocess.run(['git', '-C', db, 'rev-parse', 'HEAD'], capture_output=True,
                         text=True).stdout.strip() or 'unknown'
    rows = {}
    for f in FILES:
        for line in open(os.path.join(db, f)):
            line = line.split('#')[0].strip()
            if not line:
                continue
            parts = line.split()
            word, name, fmt, attrs = int(parts[0], 16), parts[1], parts[2], parts[3:]
            for a in attrs:
                if a.startswith('@orig_name='):
                    name = a.split('=', 1)[1]
                if a.startswith('@orig_fmt='):
                    fmt = a.split('=', 1)[1]
            if fmt == 'EMPTY':
                fmt = ''
            # The database calls the FCSR operand an integer register (D/J);
            # in assembly it is $fcsrN. 'Q' + index letter is tcc's FCSR slot.
            fmt = FCSR_FMT.get(name, fmt)
            if name in rows and rows[name] != (word, fmt):
                sys.exit(f'duplicate mnemonic {name}: {rows[name]} vs {(word, fmt)}')
            rows[name] = (word, fmt)
    print('/* LoongArch64 instructions for tcc\'s assembler: mnemonic, opcode word with')
    print('   all operand fields zero, operand format (see loongarch64-opc.py).')
    print('   GENERATED by loongarch64-opc.py from loongson-community/loongarch-opcodes')
    print(f'   commit {rev}; that data is CC-BY-4.0, Copyright (C) 2021-2023')
    print('   Contributors to the loongarch-opcodes project. Sorted for bsearch. */')
    for name in sorted(rows):
        word, fmt = rows[name]
        print(f'LA_INSN("{name}", 0x{word:08x}, "{fmt}")')


if __name__ == '__main__':
    main()
